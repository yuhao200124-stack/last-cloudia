// Bundles the fengari Lua 5.3 VM (github.com/fengari-lua/fengari, MIT) into one ES module.
// Usage: node bundle-fengari.mjs <fengari/src dir> <sprintf.js path> <out.mjs>
import fs from 'node:fs';
import path from 'node:path';
const [srcDir, sprintfPath, out] = process.argv.slice(2);
const modules = new Map();
const nodeBuiltins = ['os','fs','path','child_process','process'];
const stubs = { tmp: 'module.exports={dirSync(){return {name:"/tmp"}},fileSync(){return {name:"/tmp/x"}}};', 'readline-sync': 'module.exports={setDefaultOptions(){},question(){return ""}};' };
function add(id, file) {
  if (modules.has(id)) return;
  modules.set(id, null); // reserve first: modules require each other cyclically
  let code = fs.readFileSync(file, 'utf8');
  const dir = path.dirname(file);
  const deps = [];
  code = code.replace(/^\s*\/\/.*$/mg, '').replace(/^\s*"use strict";\s*$/m, '').replace(/process\.env\.FENGARICONF \? JSON\.parse\(process\.env\.FENGARICONF\) : \{\}/, '{}');
  code = code.replace(/require\((['"])([^'"]+)\1\)/g, (m, q, spec) => {
    let depId;
    if (spec.startsWith('.')) { const f = path.resolve(dir, spec); depId = f; add(depId, f); }
    else if (spec === 'sprintf-js') { depId = 'sprintf-js'; add(depId, sprintfPath); }
    else if (stubs[spec]) { depId = spec; if (!modules.has(spec)) modules.set(spec, stubs[spec]); }
    else if (nodeBuiltins.includes(spec)) { depId = spec; if (!modules.has(spec)) modules.set(spec, `throw new Error("fengari bundle: Node built-in ${spec} is not available in the browser build");`); }
    else throw new Error(`unknown dependency ${spec} in ${file}`);
    deps.push(depId);
    return `__require(${JSON.stringify(depId)})`;
  });
  modules.set(id, code);
}
add(path.resolve(srcDir, 'fengari.js'), path.resolve(srcDir, 'fengari.js'));
let text = `// fengari Lua 5.3 VM bundle (MIT, https://github.com/fengari-lua/fengari) + sprintf-js (BSD-3). Generated by bundle-fengari.mjs; do not edit.\n`;
text += `// The bundle always takes fengari's browser code paths (no Node process/fs/os).\nconst process = undefined;\nconst __defs = {\n`;
for (const [id, code] of modules) text += `${JSON.stringify(id)}: function(module, exports, __require) {\n${code}\n},\n`;
text += `};\nconst __cache = {};\nfunction __require(id){ if(__cache[id]) return __cache[id].exports; const module={exports:{}}; __cache[id]=module; __defs[id](module, module.exports, __require); return module.exports; }\n`;
text += `export const fengari = __require(${JSON.stringify(path.resolve(srcDir, 'fengari.js'))});\nexport default fengari;\n`;
fs.writeFileSync(out, text);
console.log('modules', modules.size, 'bytes', text.length);
