import fs from 'node:fs';
import vm from 'node:vm';
import {createHash} from 'node:crypto';
import {canonicalSkillRows, resolveSkillLabels} from '../dist/skill-labeling-model.mjs';
const root = new URL('../', import.meta.url);
const read = name => JSON.parse(fs.readFileSync(new URL(name, root), 'utf8'));
const registry = read('docs/attack-tag-registry.json');
const shared = read(registry.sharedRegistry);
if (shared.numericEffectInjection !== false) throw Error('Label metadata must not inject calculator effects.');
const resolved = resolveSkillLabels(shared);
const attackEntries = resolved.filter(entry => entry.assignedTags.includes(registry.label));
const view = shared.views.attack;
const audit = read('docs/attack-tag-audit.json');
const box = {window: {}};
vm.runInNewContext(fs.readFileSync(new URL('dist/data.js', root), 'utf8'), box);
const rows = canonicalSkillRows(box.window.SKILL_DATA);
const decisions = new Map(audit.rows.map(row => [row.id, row]));
const entries = new Map(attackEntries.map(row => [row.id, row]));
const digest = row => createHash('sha256').update(JSON.stringify([row.id,row.url,row.name,row.effect,row.notes || ''])).digest('hex');
if (registry.label !== '攻击力' || registry.numericEffectInjection !== false) throw Error('This pass must remain attack-only metadata.');
if (decisions.size !== audit.rows.length || entries.size !== registry.skillIds.length || registry.skillIds.some(id => !entries.has(id))) throw Error('Duplicate or missing review identity.');
if (view.label !== registry.label || new Set(view.displayOrder).size !== view.displayOrder.length || view.displayOrder.length !== entries.size || view.displayOrder.some(id => !entries.has(id))) throw Error('Attack view ordering drifted.');
if (rows.length !== audit.reviewedUnique || decisions.size !== rows.length) throw Error('Full-library review is incomplete.');
for (const row of rows) {
  const decision = decisions.get(row.id), entry = entries.get(row.id);
  if (!decision || decision.url !== row.url || decision.sourceHash !== digest(row)) throw Error(`Source changed; review again: ${row.id}`);
  if (!['related','not-related'].includes(decision.decision)) throw Error(`Unreviewed skill: ${row.id}`);
  if ((decision.decision === 'related') !== !!entry) throw Error(`Missing or extra attack tag: ${row.id}`);
  if (!entry) continue;
  if (entry.text !== row.effect || entry.notes !== (row.notes || '') || entry.url !== row.url) throw Error(`Tag source drift: ${row.id}`);
  if (entry.judgment !== (entry.remainingEffects.length || entry.remainingConditions.length ? 'partial' : 'ready')) throw Error(`Incomplete effect/condition coverage: ${row.id}`);
  if (!entry.attackSummary) throw Error(`Missing attack explanation: ${row.id}`);
  for (const dependency of entry.relatedSkillIds) if (!entries.has(dependency)) throw Error(`Missing linked skill: ${row.id}`);
}
if (entries.size !== audit.matchedUnique) throw Error('Related skill total drifted.');
const previous = rows.filter(row => row.basicStats?.targets.includes('攻击力'));
if (previous.length !== audit.previousBasicAttackUnique || previous.some(row => !entries.has(row.id))) throw Error('A previously known attack skill was missed.');
const counts = {
  reviewedUnique: rows.length, relatedUnique: entries.size, notRelatedUnique: rows.length - entries.size,
  ready: attackEntries.filter(entry => entry.judgment === 'ready').length,
  partial: attackEntries.filter(entry => entry.judgment === 'partial').length, unknown: 0,
  previousBasicAttackUnique: previous.length, additionalRelatedUnique: entries.size - previous.length,
};
const catalog = {...registry, entries: attackEntries, displayOrder: view.displayOrder, counts};
fs.writeFileSync(new URL('dist/attack-tag-catalog.mjs', root), `// Generated by scripts/build-attack-tags.mjs. Labels are not executable bonuses.\nexport const ATTACK_TAG_CATALOG = ${JSON.stringify(catalog, null, 2)};\n`);
console.log(JSON.stringify(counts));
