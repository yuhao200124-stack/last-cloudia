import fs from 'node:fs';
import vm from 'node:vm';
import {compileCommonEntry} from './compile-common-skills.mjs';
import {BASIC_STAT_CATALOG} from '../dist/basic-stat-catalog.mjs';
const root=new URL('../',import.meta.url);
const registry=JSON.parse(fs.readFileSync(new URL('docs/skill-labeling-registry.json',root)));
const box={window:{}};vm.runInNewContext(fs.readFileSync(new URL('dist/data.js',root),'utf8'),box);
const data=box.window.SKILL_DATA,aliases={},catalog={};
for(const entry of registry.entries){
 catalog[entry.id]={id:entry.id,name:entry.name,text:entry.text,url:entry.url,rules:compileCommonEntry(entry,{hasBasicStats:!!BASIC_STAT_CATALOG[entry.id]})};
 for(const sheet of Object.values(data.sheets))for(const row of sheet.rows||sheet.lanes.flatMap(l=>l.rows))if(row.url===entry.url)aliases[row.id]=entry.id;
}
const output=`// Generated by scripts/build-common-skill-rules.mjs. Labels do not execute.\nexport const COMMON_SKILL_CATALOG=${JSON.stringify(catalog)};\nexport const COMMON_SKILL_ALIASES=${JSON.stringify(aliases)};\n`;
const file=new URL('dist/common-skill-catalog.mjs',root);
if(process.argv.includes('--check')){if(fs.readFileSync(file,'utf8')!==output)throw Error('Common calculator rules are out of date');}
else fs.writeFileSync(file,output);
console.log(JSON.stringify({skills:Object.keys(catalog).length,ready: Object.values(catalog).flatMap(e=>e.rules).filter(r=>r.review==='ready').length,pending:Object.values(catalog).flatMap(e=>e.rules).filter(r=>r.review==='pending').length}));
