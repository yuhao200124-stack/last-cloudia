// Builds a lookup from every skill-table row id (dist/data.js) to the game database's own simplified
// name (PassiveSkillMst NAME_S). Character pages now use the game's names, while the original skill
// table (machine-translated, to be retired) keeps its own; this lookup lets the two still be matched.
//   dist/game-skill-names.js  – classic script for the main-table page: window.GAME_SKILL_NAMES
//   dist/game-skill-names.mjs – the same map for ES modules (common-skill identity)
// Source: docs/game-relic-passives.json (siteId ↔ gameId, 942 relic passives) plus the few skills
// that are not relic-learnable, looked up by id in dist/game-data/engine/passive-index.json.
import fs from 'node:fs';
import vm from 'node:vm';
const root=new URL('../',import.meta.url);
const read=p=>fs.readFileSync(new URL(p,root),'utf8');
const game=JSON.parse(read('docs/game-relic-passives.json'));
const index=JSON.parse(read('dist/game-data/engine/passive-index.json'));
const byGameId=new Map(index.rows.map(r=>[r[0],r[2]]));
// Skill-table rows whose passive is not in the relic export; verified by hand against the game data.
const extra={'e012b3fe60fe4932':9300}; // 麻痹研究 → 麻痺研究 (the relic export had wrongly paired it with 9400 疾病研究)
const box={window:{}};vm.runInNewContext(read('dist/data.js'),box);
const rows=box.window.SKILL_DATA.sheets['全部技能'].rows.filter(r=>!r.separator);
const names={};
for(const g of game)if(g.siteId)names[g.siteId]=g.nameS;
for(const [siteId,gameId] of Object.entries(extra)){
 if(names[siteId])throw Error(`Duplicate mapping for ${siteId}`);
 const nameS=byGameId.get(gameId);if(!nameS)throw Error(`Unknown passive ${gameId}`);
 names[siteId]=nameS;
}
const missing=rows.filter(r=>!names[r.id]);
if(missing.length)throw Error(`No game name for: ${missing.map(r=>r.name).join('、')}`);
const ordered=Object.fromEntries(rows.map(r=>[r.id,names[r.id]]));
const json=JSON.stringify(ordered);
// Characters whose pages existed before they switched to game names: new name → earlier name, so the
// loadout keeps binding their skills to the same table rows as before.
const renames=JSON.parse(read('docs/game-name-map-2026-09-28.json')).characters;
const legacy=JSON.stringify(Object.fromEntries(Object.entries(renames).map(([id,c])=>[id,Object.fromEntries(Object.values(c.groups).flat().map(([oldName,newName])=>[newName,oldName]))])));
fs.writeFileSync(new URL('dist/game-skill-names.mjs',root),`// Generated by scripts/build-game-skill-names.mjs. Skill-table id → game database name (NAME_S).\nexport const GAME_SKILL_NAMES=${json};\n`);
fs.writeFileSync(new URL('dist/game-skill-names.js',root),`// Generated by scripts/build-game-skill-names.mjs. Skill-table id → game database name (NAME_S).\n// Only a lookup: the main skill table keeps displaying its own names; the loadout uses this to\n// bind a character's own skills (named as in the game) to the matching table rows.\nwindow.GAME_SKILL_NAMES=${json};\nwindow.CHARACTER_SKILL_LEGACY_NAMES=${legacy};\n`);
const changed=rows.filter(r=>ordered[r.id]!==r.name).length;
console.log(JSON.stringify({rows:rows.length,renamed:changed}));
