// Builds dist/game-skill-data.js: the skill table with the game's own names, SC, effects and relics.
// Source: docs/game-relic-passives.json (exported from PassiveSkillMst / ArkMst, 942 passives learnable from relics)
// Layout (tabs, lanes, type groups, order, rating) follows dist/data.js.
import fs from 'node:fs';
import vm from 'node:vm';
const root=new URL('../',import.meta.url);
const game=JSON.parse(fs.readFileSync(new URL('docs/game-relic-passives.json',root),'utf8'));
const box={window:{}};vm.runInNewContext(fs.readFileSync(new URL('dist/data.js',root),'utf8'),box);
const site=box.window.SKILL_DATA;
const bySite=new Map(game.filter(g=>g.siteId).map(g=>[g.siteId,g]));
const skills={};
for(const g of game){
 const s=g.siteId?site.sheets['全部技能'].rows.find(r=>r.id===g.siteId):null;
 skills[g.gameId]={id:`g${g.gameId}`,gameId:g.gameId,name:g.name,nameS:g.nameS,sc:String(g.sc),ap:g.ap,effect:g.effect,effectS:g.effectS,
  values:/\?/.test(g.effect)?g.values:'',io:g.io||'',
  sources:g.relics.map(r=>`${r.name}（${r.rarity}）`),sourcesS:g.relics.map(r=>`${r.nameS}（${r.rarity}）`),
  mark:s?.mark||'',siteName:s?.name||'',siteSc:s?String(s.sc):'',siteEffect:s?.effect||'',url:s?.url||''};
}
const convert=row=>{
 if(row.separator)return {separator:true};
 const g=bySite.get(row.id);
 return g?{ref:g.gameId,type:row.type}:null;
};
const sheets={},order=[...site.sheetOrder];
for(const name of order){
 const sh=site.sheets[name];
 if(sh.kind==='all')sheets[name]={kind:'all',rows:sh.rows.map(convert).filter(Boolean)};
 else sheets[name]={kind:sh.kind==='basicStats'?'lanes':'split',lanes:sh.lanes.map(l=>({label:l.label||null,rows:l.rows.map(convert).filter(Boolean)}))};
}
const missing=game.filter(g=>!g.siteId).map(g=>({ref:g.gameId}));
sheets['全部技能'].rows.push(...missing);
// Relic passives the original table does not have yet go to 杂项 for now.
sheets['杂项'].lanes[0].rows.push({separator:true},...missing.map(m=>({...m,type:'原表未收录'})));
const out={generatedFrom:'游戏主数据 PassiveSkillMst / ArkMst（可从圣物学习的被动）',total:game.length,siteMatched:game.length-missing.length,sheetOrder:order,sheets,skills};
fs.writeFileSync(new URL('dist/game-skill-data.js',root),`// Generated by scripts/build-game-skill-table.mjs\nwindow.GAME_SKILL_DATA=${JSON.stringify(out)};\n`);
console.log(JSON.stringify({total:game.length,missing:missing.length,sheets:order.length}));
